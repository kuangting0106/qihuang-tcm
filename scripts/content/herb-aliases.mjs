// 不合并：桂枝 / 牡桂 / 肉桂（药用部位不同，桂枝单列，牡桂与菌桂归肉桂）；
// 干地黄 / 生地黄 / 熟地黄（炮制规格不同）；白术 / 苍术；赤芍 / 白芍；
// 枳实 / 枳壳（同一植物不同成熟度，保留两条并互注）；甜杏仁 / 杏仁。

export const canonicalName = (() => {
  const map = new Map()
  for (const group of herbAliasGroups) {
    map.set(group.canonical, group.canonical)
    for (const alias of group.aliases) map.set(alias, group.canonical)
  }
  return (name) => map.get(name) ?? name
})()
